#!/bin/sh
# Madire OS (0.10): turns the linked built-in user programs into raw blobs
# and writes the table of images (struct userimg, kernel/proc/userimg.h) as
# NASM source on stdout.
#
#   sh scripts/user-images.sh <dir> <program>...     (<dir>/<program>.elf)
#
# Each program must have only .text (at 0x400000: code + read-only data),
# .data and .bss (from 0x500000) as loaded sections, must start at its ELF
# entry point inside .text (1.0 stage 7: e_entry, which is _start for every
# program but args, whose own stub jumps to _start), and must not use
# x87/MMX/SSE registers (except `fpu`, whose purpose is to use them, and
# which must). Any other case fails the build.
# The output depends only on the programs: sorted, no dates.
set -eu
LC_ALL=C
export LC_ALL

dir=$1
shift
TEXT=0x400000
DATA=0x500000

fail() { echo "user-images.sh: $*" >&2; exit 1; }

# symbol value (hex, no 0x) from nm, or empty
sym() { nm "$1" | S="$2" awk '$3 == ENVIRON["S"] { print $1 }'; }

echo "; Generated by scripts/user-images.sh from $dir/*.elf (0.10). Do not edit."
echo "; struct userimg: name, text, text_size, data, data_size, data_mem, entry"
echo ""
echo "bits 64"
echo "section .rodata"
echo ""

count=0
for p in "$@"; do
    elf=$dir/$p.elf
    [ -f "$elf" ] || fail "$elf missing"

    # Loaded (ALLOC) sections: exactly .text, and optionally .data / .bss.
    alloc=$(objdump -h -w "$elf" | awk '$1 ~ /^[0-9]+$/ && /ALLOC/ { print $2 }' | tr '\n' ' ')
    for s in $alloc; do
        case $s in .text|.data|.bss) ;; *) fail "$p: unexpected loaded section $s" ;; esac
    done
    case " $alloc" in *" .text "*) ;; *) fail "$p: no .text" ;; esac

    tvma=$(objdump -h -w "$elf" | awk '$2 == ".text" { print $4 }')
    [ "$((0x$tvma))" -eq "$((TEXT))" ] || fail "$p: .text at 0x$tvma, not $TEXT"
    dvma=$(objdump -h -w "$elf" | awk '$2 == ".data" { print $4 }')
    if [ -n "$dvma" ]; then
        [ "$((0x$dvma))" -eq "$((DATA))" ] || fail "$p: .data at 0x$dvma, not $DATA"
    fi

    # Registers, as for the kernel (Makefile), plus x87/MMX instructions that
    # name no register (fld1, emms). -mgeneral-regs-only means the compiler
    # never emits these; only inline assembly could.
    if objdump -d "$elf" | grep -qE '%(x|y|z)?mm[0-9]|%st|[[:space:]](fld1|fldz|emms)([[:space:]]|$)'; then
        [ "$p" = fpu ] || fail "$p: uses x87/MMX/SSE"
    else
        [ "$p" != fpu ] || fail "fpu: does not use x87/MMX/SSE (it is the test of that)"
    fi

    objcopy -O binary -j .text "$elf" "$dir/$p.text.bin"
    objcopy -O binary -j .data "$elf" "$dir/$p.data.bin"
    tsize=$(wc -c < "$dir/$p.text.bin" | tr -d ' ')
    dsize=$(wc -c < "$dir/$p.data.bin" | tr -d ' ')
    # 16 hex digits, as nm printed _start's value until 1.0 stage 7.
    entry=$(readelf -h "$elf" | awk '$1 == "Entry" && $2 == "point" { print $4 }')
    [ -n "$entry" ] && entry=$(printf '%016x' "$(($entry))")
    bend=$(sym "$elf" __bss_end)
    [ -n "$entry" ] && [ -n "$bend" ] || fail "$p: entry point or __bss_end missing"
    dmem=$((0x$bend - DATA))
    [ "$dmem" -ge "$dsize" ] || fail "$p: bss ends before the data"
    [ "$tsize" -gt 0 ] && [ "$tsize" -le 65536 ] || fail "$p: code size $tsize"
    [ "$dmem" -le 65536 ] || fail "$p: data + bss size $dmem"
    [ "$((0x$entry))" -ge "$((TEXT))" ] && [ "$((0x$entry - TEXT))" -lt "$tsize" ] ||
        fail "$p: entry point 0x$entry outside the code"

    echo "align 16"
    echo "img_${p}_name: db \"$p\", 0"
    echo "align 16"
    echo "img_${p}_text: incbin \"$dir/$p.text.bin\"   ; $tsize bytes"
    echo "align 16"
    echo "img_${p}_data: incbin \"$dir/$p.data.bin\"   ; $dsize bytes, $dmem with bss"
    echo ""
    eval "t_$count=\$p s_$count=\$tsize d_$count=\$dsize m_$count=\$dmem e_$count=0x\$entry"
    count=$((count + 1))
done

echo "align 16"
echo "global user_images"
echo "global user_images_count"
echo "user_images_count: dq $count"
echo "user_images:"
i=0
while [ "$i" -lt "$count" ]; do
    eval "p=\$t_$i s=\$s_$i d=\$d_$i m=\$m_$i e=\$e_$i"
    echo "    dq img_${p}_name, img_${p}_text, $s, img_${p}_data, $d, $m, $e"
    i=$((i + 1))
done
echo ""
echo "section .note.GNU-stack noalloc noexec nowrite progbits"
