#!/usr/bin/env python3
"""Converts one pinned BDF font file to C (1.2 stage 6; standard library only).

    make-font.py BDF OUT.c NAME [--sums SHA256SUMS]

Reads BDF (a bitmap font of fixed cell size: every glyph's BBX must be the
FONTBOUNDINGBOX), keeps the 256 glyphs of code page 437 in code page order
and writes OUT.c: an array of 256 x height rows of ceil(width / 8) bytes,
the leftmost pixel in the top bit of the first byte, and the struct font
NAME (kernel/display/font.h). With --sums, the file's SHA-256 must be the
one SHA256SUMS lists for its file name, or nothing is written.

Code page 437 to Unicode: 0x20-0x7E are ASCII; 0x80-0xFF follow Python's
cp437 codec; 0x01-0x1F and 0x7F are the code page's graphic characters
(the table below); 0x00 is drawn as a space, as the VGA's own font does.
A missing glyph is an error. The output depends only on the input: the
same BDF file always gives the same bytes (checked in part static).

Exit status 0 on success; 1 with "make-font: ERROR: ..." on any error.
"""
import hashlib
import os
import sys

# Code page 437's graphic characters for the control codes 0x01-0x1F.
CP437_LOW = [
    0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022, 0x25D8,
    0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C, 0x25BA,
    0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8, 0x2191,
    0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC,
]


def cp437_to_unicode(byte):
    if byte == 0x00:
        return 0x20
    if byte < 0x20:
        return CP437_LOW[byte - 1]
    if byte == 0x7F:
        return 0x2302
    return ord(bytes([byte]).decode("cp437"))


class FontError(Exception):
    pass


def parse_bdf(text):
    """(width, height, {encoding: [row bytes]}) of a fixed-cell BDF font."""
    lines = text.split("\n")
    if not lines or not lines[0].startswith("STARTFONT "):
        raise FontError("not a BDF file (no STARTFONT)")
    box = None
    glyphs = {}
    i = 0
    while i < len(lines):
        words = lines[i].split()
        if words and words[0] == "FONTBOUNDINGBOX":
            box = tuple(int(w) for w in words[1:5])
        elif words and words[0] == "STARTCHAR":
            if box is None:
                raise FontError("a glyph before FONTBOUNDINGBOX")
            enc, bbx, rows = None, None, None
            i += 1
            while i < len(lines) and lines[i] != "ENDCHAR":
                w = lines[i].split()
                if w and w[0] == "ENCODING":
                    enc = int(w[1])
                elif w and w[0] == "BBX":
                    bbx = tuple(int(x) for x in w[1:5])
                elif w and w[0] == "BITMAP":
                    rows = []
                    i += 1
                    while i < len(lines) and lines[i] != "ENDCHAR":
                        rows.append(lines[i])
                        i += 1
                    break
                i += 1
            if i >= len(lines):
                raise FontError("glyph %s: no ENDCHAR" % words[1:])
            if enc is None or bbx is None or rows is None:
                raise FontError("glyph %s: no ENCODING, BBX or BITMAP" % words[1:])
            if bbx != box:
                raise FontError("glyph %d: BBX %s is not the FONTBOUNDINGBOX %s" % (enc, bbx, box))
            width, height = box[0], box[1]
            row_bytes = (width + 7) // 8
            if len(rows) != height:
                raise FontError("glyph %d: %d rows, expected %d" % (enc, len(rows), height))
            data = []
            for r in rows:
                if len(r) != 2 * row_bytes:
                    raise FontError("glyph %d: row %r is not %d hex digits" % (enc, r, 2 * row_bytes))
                b = bytes.fromhex(r)
                spare = row_bytes * 8 - width
                if spare and b[-1] & ((1 << spare) - 1):
                    raise FontError("glyph %d: pixels past the cell's width" % enc)
                data.append(b)
            if enc >= 0:
                if enc in glyphs:
                    raise FontError("glyph %d twice" % enc)
                glyphs[enc] = data
        i += 1
    if box is None:
        raise FontError("no FONTBOUNDINGBOX")
    return box[0], box[1], glyphs


def expected_hash(sums_path, name):
    with open(sums_path, encoding="ascii") as f:
        for line in f:
            parts = line.split()
            if len(parts) == 2 and parts[1] == name:
                return parts[0]
    raise FontError("%s lists no SHA-256 for %s" % (sums_path, name))


def to_c(width, height, glyphs, name, source, digest):
    row_bytes = (width + 7) // 8
    out = [
        "/* Generated by scripts/make-font.py from %s" % source,
        " * (SHA-256 %s). Do not edit." % digest,
        " * The 256 glyphs of code page 437, %u x %u pixels: %u rows of %u byte%s each," % (
            width, height, height, row_bytes, "" if row_bytes == 1 else "s"),
        " * the leftmost pixel in the top bit. Licence: SIL Open Font License 1.1",
        " * (third_party/terminus/OFL.txt; THIRD_PARTY_ASSETS.md). */",
        '#include "kernel/display/font.h"',
        "",
        "static const uint8_t bits[256 * %u] = {" % (height * row_bytes),
    ]
    for byte in range(256):
        u = cp437_to_unicode(byte)
        if u not in glyphs:
            raise FontError("no glyph for code page 437 byte 0x%02X (U+%04X)" % (byte, u))
        flat = b"".join(glyphs[u])
        out.append("    /* 0x%02X U+%04X */" % (byte, u))
        for k in range(0, len(flat), 16):
            out.append("    " + " ".join("0x%02x," % v for v in flat[k:k + 16]))
    out += [
        "};",
        "",
        "const struct font %s = { %u, %u, %u, bits };" % (name, width, height, row_bytes),
        "",
    ]
    return "\n".join(out)


def main():
    args = sys.argv[1:]
    sums = None
    if "--sums" in args:
        k = args.index("--sums")
        if k + 1 >= len(args):
            print("make-font: ERROR: --sums needs a file")
            return 1
        sums = args[k + 1]
        del args[k:k + 2]
    if len(args) != 3:
        print(__doc__)
        return 1
    bdf, out_path, name = args
    try:
        with open(bdf, "rb") as f:
            raw = f.read()
        digest = hashlib.sha256(raw).hexdigest()
        if sums is not None:
            want = expected_hash(sums, os.path.basename(bdf))
            if digest != want:
                raise FontError("%s: SHA-256 %s, SHA256SUMS pins %s" % (bdf, digest, want))
        width, height, glyphs = parse_bdf(raw.decode("ascii"))
        source = "third_party/terminus/" + os.path.basename(bdf)
        text = to_c(width, height, glyphs, name, source, digest)
    except (OSError, ValueError, UnicodeDecodeError, FontError) as e:
        print("make-font: ERROR: %s" % e)
        return 1
    with open(out_path + ".tmp", "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    os.replace(out_path + ".tmp", out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
