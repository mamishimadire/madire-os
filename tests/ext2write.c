/* Madire OS: the ext2 write core as a host tool (1.4 stage 9; docs/plans/
 * 1.4.md, S9, C5 with R1-R4, section D). Built from the SAME pure files the
 * kernel will link in stage 10, kernel/fs/ext2_write.c, kernel/fs/
 * ext2_core.c and kernel/storage/blk_core_save.c (none of them linked into
 * the kernel in stage 9). Part static runs it on images made by mke2fs and
 * checks the result with e2fsck -fn and debugfs (tests/ext2_cut.py).
 *
 *   ext2write [-c <N>] <filesystem image> <sequence>
 *   ext2write -t                      (the SHA-256 self-test only)
 *
 * Runs one fixed operation sequence (owner, hardlink, dirs, rmdir, indirect, grow,
 * all, recount, readonly) on the image, saving as the sequence says (and
 * when the core asks for it: EXT2_EAGAIN, R4, at most 3 saves for one
 * operation), then a full save and the unmount (the clean state). With -c,
 * the disk takes only the first N write commands; the (N + 1)th and every
 * later write fails as at a power cut, and the tool stops ("CUT after N").
 *
 * It keeps its own model of the tree (paths, modes, sizes, contents as
 * generated byte patterns over the imported files), independent of the
 * core, and prints:
 *   W <n> save <s> class <c> off <byte> len <bytes>   each write command
 *   S <k> done <writes>                 save k finished
 *   K <k> P <path> mode= size= links= sha=   the model's tree when save k
 *                                       finished (k = -1: the imported tree)
 *   C <k> <kind> <path>                 a path changed by save k's work
 *                                       (new, data, del, from, to)
 *   T <k> <ino>                         an inode changed by save k's work
 *   R <k> hard|dir|parent <ino>         an R3 step started by save k's work (a
 *                                       hard-linked name, a folder removed, its parent)
 *   M <k> <ino>                         a folder moved to another folder by save k's work
 *   I <ino> <path>                      an inode's path (imported, created or made)
 *   B <path> <blocks...>                a file's data blocks (owner case)
 *   O <operation> ...                   each operation and its result
 *   MOUNT rw=<0|1> why=<text> recounted=<0|1>
 *   DONE writes=<n> saves=<n>, then P lines: the expected tree at the end
 * Exit status: 0 done (or cut), 3 usage, file or self-test, 4 an operation
 * gave an unexpected result (FAIL line). */
